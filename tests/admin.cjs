const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const assert = require('node:assert/strict');
const {JSDOM} = require('jsdom');

const root = path.join(__dirname, '..');
const php = process.env.PHP_BIN || 'php';
const html = execFileSync(php, [path.join(__dirname, 'render.php'), '--html'], {encoding: 'utf8'});
const css = fs.readFileSync(path.join(root, 'assets/admin.css'), 'utf8');
const dom = new JSDOM(`<style>${css}</style><form>${html}</form>`, {runScripts: 'outside-only'});
const {document, Event, KeyboardEvent, FormData} = dom.window;
dom.window.eval(fs.readFileSync(path.join(root, 'assets/admin.js'), 'utf8'));

const input = document.querySelector('#wpcunter-font_size');
const mobile = document.querySelector('#wpcunter-font_size_mobile');
const field = input.closest('.wpcunter-responsive');
const mobileButton = field.querySelector('[data-device=mobile]');
mobileButton.click();
assert.equal(input.hidden, true);
assert.equal(mobile.hidden, false);
assert.equal(field.querySelector('label').htmlFor, mobile.id);
assert.equal(mobileButton.getAttribute('aria-pressed'), 'true');
mobile.value = '22.5';
mobile.dispatchEvent(new Event('input', {bubbles: true}));
assert.equal(mobileButton.classList.contains('has-value'), true);
assert.equal(new FormData(document.querySelector('form')).get('wpcunter_settings[font_size_mobile]'), '22.5');
field.querySelector('[data-device=desktop]').click();
assert.equal(mobile.value, '22.5', 'Switching device preserves values');
assert.equal(mobile.hidden, true);
assert.equal(dom.window.getComputedStyle(input).height, '42px');
assert.equal(dom.window.getComputedStyle(document.querySelector('#wpcunter-font_weight')).height, '42px');

const scheme = document.querySelector('#wpcunter-color_scheme');
assert.equal(document.querySelector('[data-field=color]').hidden, true);
scheme.value = 'custom';
scheme.dispatchEvent(new Event('change', {bubbles: true}));
assert.equal(document.querySelector('[data-field=color]').hidden, false);
assert.equal(document.querySelector('[data-layout=animation_position]'), null);
assert.equal(document.querySelector('[data-layout=vertical_align]'), null);
assert.equal(document.querySelector('[data-layout=align]'), null);
const animation = document.querySelector('#wpcunter-counter_animation');
animation.value = 'none';
animation.dispatchEvent(new Event('change', {bubbles: true}));

assert.equal(document.querySelector('[role=tablist]'), null);
assert.equal(document.querySelector('#wpcunter-panel-design'), null);
const animationRow = document.querySelector('.wpcunter-animation-fields');
assert.deepEqual(Array.from(animationRow.children).map(node => node.dataset.field), ['counter_animation', 'duration', 'slow_down']);
assert.ok(dom.window.getComputedStyle(animationRow).gridTemplateColumns.includes('2fr'), 'Effect keeps half of the three-control row');
const slowdown = document.querySelector('#wpcunter-slow_down');
assert.equal(slowdown.checked, true);
slowdown.checked = false;
assert.deepEqual(new FormData(document.querySelector('form')).getAll('wpcunter_settings[slow_down]'), ['0'], 'Unchecked option submits false');
assert.equal(document.querySelectorAll('input[name="wpcunter_settings[label]"]').length, 1);
assert.equal(document.querySelector('#wpcunter-label').closest('.wpcunter-column-left') !== null, true);
assert.equal(document.querySelector('#wpcunter-counter_animation').closest('.wpcunter-column-right') !== null, true);
assert.equal(document.querySelector('#wpcunter-color_scheme').closest('.wpcunter-column-left') !== null, true);
assert.equal(document.querySelector('#wpcunter-el_class').closest('.wpcunter-column-left') !== null, true);
assert.equal(document.querySelector('#wpcunter-size'), null);
assert.equal(document.querySelector('#wpcunter-label_size'), null);
assert.equal(document.querySelector('[data-field=ring_color]').hidden, true);
animation.value = 'ring';
animation.dispatchEvent(new Event('change', {bubbles: true}));
for (const key of ['ring_color', 'ring_thickness', 'ring_size']) assert.equal(document.querySelector(`[data-field=${key}]`).hidden, false);
const ringGroup=document.querySelector('.wpcunter-ring-fields');
assert.equal(document.querySelector('.wpcunter-marker-fields').hidden, true);
assert.equal(ringGroup.hidden, false);
animation.value = 'ring_band';
animation.dispatchEvent(new Event('change', {bubbles: true}));
assert.equal(document.querySelector('[data-field=ring_thickness] label').textContent, 'Gradient thickness, px');
assert.equal(document.querySelector('[data-field=ring_color] label').textContent, 'Gradient color');
assert.ok(document.querySelector('[data-effect-description]').textContent.includes('No outline'));
assert.equal(document.querySelector('.wpcunter-marker-fields').hidden, false);
assert.equal(ringGroup.hidden, false);
assert.deepEqual(Array.from(ringGroup.children).map(node => node.dataset.field), ['ring_size','ring_thickness','ring_color']);
const ringSize=document.querySelector('[data-field=ring_size]');
ringSize.querySelector('[data-device=mobile]').click();
assert.equal(document.querySelector('#wpcunter-ring_size_mobile').hidden, false);
assert.equal(document.querySelector('#wpcunter-ring_size').hidden, true);
assert.equal(document.querySelector('[data-field=ring_thickness] .wpcunter-devices') !== null, true);
animation.value = 'ring_marker';
animation.dispatchEvent(new Event('change', {bubbles: true}));
assert.equal(document.querySelector('[data-field=ring_thickness] label').textContent, 'Ring thickness, px');
assert.equal(document.querySelector('.wpcunter-marker-fields').hidden, false);
assert.equal(ringGroup.hidden, false);
animation.value = 'none';
animation.dispatchEvent(new Event('change', {bubbles: true}));
assert.equal(document.querySelector('[data-field=ring_color]').hidden, true);
assert.equal(ringGroup.hidden, true);
dom.window.close();
console.log('PASS: admin DOM, device switching, value persistence, dependencies, equal heights and columns');
