const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../assets/frontend.js'), 'utf8');
function run(start, final, reduced = false, supportsObserver = true, hasRing = false, slowDown = false, hasMarker = false, hasBand = false) {
    const frames = [];
    const number = {textContent: String(final), style: {}, getBoundingClientRect() { return {width: Array.from(this.textContent).reduce((sum, char) => sum + (char === '1' ? 5 : 9), 0)}; }};
    const attributes = {'stroke-dashoffset': '0'};
    const markerAttributes = {};
    const marker = {setAttribute: (name, value) => { markerAttributes[name] = value; }};
    const bandAttributes = {};
    const bandStyle = {};
    const band = {setAttribute: (name, value) => { bandAttributes[name] = value; }};
    const sweep = hasMarker ? 83.333333 : 100;
    const arc = {dataset: {sweep: String(sweep), startAngle: hasMarker ? '120' : '-90'}, parentNode: {style: {setProperty: (name, value) => { bandStyle[name] = value; }}, querySelector: selector => selector === '.wpcunter-marker-orbit' ? (hasMarker ? marker : null) : (hasBand ? band : null)}, setAttribute: (name, value) => { attributes[name] = value; }};
    const value = {dataset: {start: String(start), final: String(final), duration: '3000', slowDown: slowDown ? '1' : '0'}, isConnected: true, querySelector: () => number, closest: () => hasRing ? {querySelector: () => arc} : null};
    let intersection;
    const window = {matchMedia: () => ({matches: reduced}), requestAnimationFrame: fn => frames.push(fn), addEventListener() {}};
    if (supportsObserver) window.IntersectionObserver = true;
    const document = {nodeType: 9, readyState: 'complete', body: {}, querySelectorAll: () => [value]};
    vm.runInNewContext(source, {window, document, IntersectionObserver: class {constructor(fn) {intersection = fn;} observe() {} unobserve() {}}, MutationObserver: class {observe() {}}});
    assert.equal(number.textContent, String(supportsObserver || reduced ? final : start));
    if (supportsObserver) intersection([{isIntersecting: true, target: value}]);
    const reservedWidth = number.style.minWidth;
    if (!reduced && start !== final) {
        frames.shift()(0);
        assert.equal(number.textContent, String(start));
        if (hasRing) assert.equal(Number(attributes['stroke-dashoffset']), sweep);
        if (hasMarker) assert.equal(markerAttributes.transform, 'rotate(120 50 50)');
        frames.shift()(1500);
        assert.equal(number.style.minWidth, reservedWidth, 'Number width stays fixed during counting');
        assert.ok(parseFloat(reservedWidth) >= number.getBoundingClientRect().width, 'Reserved width contains intermediate digits');
        const midpoint = Number(number.textContent);
        assert.ok(midpoint >= Math.min(start, final) && midpoint <= Math.max(start, final));
        const fraction = slowDown ? .9375 : .5;
        assert.equal(midpoint, Math.ceil(start + (final - start) * fraction));
        if (hasRing) assert.ok(Math.abs(Number(attributes['stroke-dashoffset']) - sweep * (1 - fraction)) < .001);
        if (hasMarker) assert.ok(Math.abs(parseFloat(markerAttributes.transform.slice(7)) - (120 + sweep * 3.6 * fraction)) < .001);
        if (hasBand) assert.equal(bandAttributes['stroke-dashoffset'], attributes['stroke-dashoffset']);
        if (hasBand) assert.ok(Math.abs(parseFloat(bandStyle['--wpcunter-band-fill']) - sweep * 3.6 * fraction) < .001);
        frames.shift()(3000);
    }
    assert.equal(number.textContent, String(final));
    assert.equal(number.style.minWidth, reservedWidth, 'Width stays fixed at completion');
    if (hasRing) assert.equal(Number(attributes['stroke-dashoffset']), 0);
    if (hasMarker) assert.ok(Math.abs(parseFloat(markerAttributes.transform.slice(7)) - 420) < .001);
    if (hasBand) assert.equal(Number(bandAttributes['stroke-dashoffset']), 0);
    if (supportsObserver) intersection([{isIntersecting: true, target: value}]);
    assert.equal(frames.length, 0);
}
